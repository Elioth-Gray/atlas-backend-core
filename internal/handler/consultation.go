// ConsultationService is the business logic ConsultationHandler depends on.
type ConsultationService interface {
	Start(ctx context.Context, userID, issueID, requestID uuid.UUID) (service.SessionView, error)
	Get(ctx context.Context, userID, sessionID uuid.UUID) (service.SessionView, error)
	Turn(ctx context.Context, userID, sessionID uuid.UUID, in service.TurnInput) (service.SessionView, error)
	Save(ctx context.Context, userID, sessionID uuid.UUID, in service.SaveInput) (service.SaveResult, error)
}

// MemoryService is the business logic behind business memories.
type MemoryService interface {
	List(ctx context.Context, userID, shopID uuid.UUID, active *bool, params service.PageParams) (service.Page[domain.BusinessMemory], error)
	Update(ctx context.Context, userID, memoryID uuid.UUID, in service.UpdateMemoryInput) (domain.BusinessMemory, error)
}

// ConsultationHandler serves the guided AI consultation and business memory endpoints.
type ConsultationHandler struct {
	consultations ConsultationService
	memories      MemoryService
}

// NewConsultationHandler returns a ConsultationHandler.
func NewConsultationHandler(consultations ConsultationService, memories MemoryService) *ConsultationHandler {
	return &ConsultationHandler{consultations: consultations, memories: memories}
}

// startConsultationRequest is the body of POST /owner/issues/:issueId/consultations.
// request_id is generated by the client and reused when retrying.
type startConsultationRequest struct {
	RequestID string `json:"request_id" binding:"required,uuid"`
}

// turnRequest is the body of POST /owner/consultations/:sessionId/turns.
type turnRequest struct {
	RequestID    string `json:"request_id" binding:"required,uuid"`
	StateVersion int64  `json:"state_version" binding:"required,min=1"`
	Event        string `json:"event" binding:"required,oneof=OWNER_REPLY SKIP_QUESTION GENERATE_NOW CONTINUE_DISCUSSION"`
	Content      string `json:"content" binding:"max=4000"`
}

// confirmedMemoryRequest is a memory candidate the owner approved (possibly edited).
type confirmedMemoryRequest struct {
	FactText              string   `json:"fact_text" binding:"required,min=1,max=1000"`
	SourceOwnerMessageIDs []string `json:"source_owner_message_ids" binding:"required,min=1,max=50,dive,uuid"`
}

// saveConsultationRequest is the body of POST /owner/consultations/:sessionId/save.
type saveConsultationRequest struct {
	FinalSolutionMessageID string                   `json:"final_solution_message_id" binding:"required,uuid"`
	StateVersion           *int64                   `json:"state_version" binding:"omitempty,min=1"`
	ConfirmedMemories      []confirmedMemoryRequest `json:"confirmed_memories" binding:"omitempty,max=20,dive"`
}

// listMemoriesQuery is the query string of GET /owner/shops/:shopId/memories.
type listMemoriesQuery struct {
	Page     int   `form:"page" binding:"omitempty,min=1,max=100000"`
	PageSize int   `form:"page_size" binding:"omitempty,min=1,max=100"`
	IsActive *bool `form:"is_active"`
}

// updateMemoryRequest is the body of PATCH /owner/memories/:memoryId.
type updateMemoryRequest struct {
	FactText *string `json:"fact_text" binding:"omitempty,min=1,max=1000"`
	IsActive *bool   `json:"is_active"`
}

// Start handles POST /api/v1/owner/issues/:issueId/consultations. It answers 201 for a new
// session and 200 when the request_id was already processed.
func (h *ConsultationHandler) Start(c *gin.Context) {
	userID, issueID, ok := userAndUUID(c, "issueId")
	if !ok {
		return
	}
	var req startConsultationRequest
	if err := bindJSON(c, &req); err != nil {
		handleError(c, err)
		return
	}
	view, err := h.consultations.Start(c.Request.Context(), userID, issueID, uuid.MustParse(req.RequestID))
	if err != nil {
		handleError(c, err)
		return
	}
	status := http.StatusCreated
	if view.Replayed {
		status = http.StatusOK
	}
	c.JSON(status, httpx.DataResponse[sessionResponse]{Data: newSessionResponse(view)})
}

// Get handles GET /api/v1/owner/consultations/:sessionId.
func (h *ConsultationHandler) Get(c *gin.Context) {
	userID, sessionID, ok := userAndUUID(c, "sessionId")
	if !ok {
		return
	}
	view, err := h.consultations.Get(c.Request.Context(), userID, sessionID)
	if err != nil {
		handleError(c, err)
		return
	}
	c.JSON(http.StatusOK, httpx.DataResponse[sessionResponse]{Data: newSessionResponse(view)})
}

// Turn handles POST /api/v1/owner/consultations/:sessionId/turns.
func (h *ConsultationHandler) Turn(c *gin.Context) {
	userID, sessionID, ok := userAndUUID(c, "sessionId")
	if !ok {
		return
	}
	var req turnRequest
	if err := bindJSON(c, &req); err != nil {
		handleError(c, err)
		return
	}
	view, err := h.consultations.Turn(c.Request.Context(), userID, sessionID, service.TurnInput{
		RequestID:    uuid.MustParse(req.RequestID),
		StateVersion: req.StateVersion,
		Event:        domain.TurnEvent(req.Event),
		Content:      req.Content,
	})
	if err != nil {
		handleError(c, err)
		return
	}
	c.JSON(http.StatusOK, httpx.DataResponse[sessionResponse]{Data: newSessionResponse(view)})
}

// Save handles POST /api/v1/owner/consultations/:sessionId/save.
func (h *ConsultationHandler) Save(c *gin.Context) {
	userID, sessionID, ok := userAndUUID(c, "sessionId")
	if !ok {
		return
	}
	var req saveConsultationRequest
	if err := bindJSON(c, &req); err != nil {
		handleError(c, err)
		return
	}
	in := service.SaveInput{
		FinalSolutionMessageID: uuid.MustParse(req.FinalSolutionMessageID),
		StateVersion:           req.StateVersion,
		ConfirmedMemories:      make([]service.MemoryInput, 0, len(req.ConfirmedMemories)),
	}
	for _, m := range req.ConfirmedMemories {
		in.ConfirmedMemories = append(in.ConfirmedMemories, service.MemoryInput{
			FactText: m.FactText, SourceOwnerMessageIDs: parseUUIDs(m.SourceOwnerMessageIDs),
		})
	}
	res, err := h.consultations.Save(c.Request.Context(), userID, sessionID, in)
	if err != nil {
		handleError(c, err)
		return
	}
	out := saveConsultationResponse{Session: newSessionResponse(res.View), Memories: make([]memoryResponse, 0, len(res.Memories))}
	for _, m := range res.Memories {
		out.Memories = append(out.Memories, newMemoryResponse(m))
	}
	c.JSON(http.StatusOK, httpx.DataResponse[saveConsultationResponse]{Data: out})
}

// ListMemories handles GET /api/v1/owner/shops/:shopId/memories.
func (h *ConsultationHandler) ListMemories(c *gin.Context) {
	userID, shopID, ok := userAndUUID(c, "shopId")
	if !ok {
		return
	}
	var q listMemoriesQuery
	if err := bindQuery(c, &q); err != nil {
		handleError(c, err)
		return
	}
	page, err := h.memories.List(c.Request.Context(), userID, shopID, q.IsActive, service.PageParams{Page: q.Page, PageSize: q.PageSize})
	if err != nil {
		handleError(c, err)
		return
	}
	out := make([]memoryResponse, 0, len(page.Items))
	for _, m := range page.Items {
		out = append(out, newMemoryResponse(m))
	}
	c.JSON(http.StatusOK, httpx.ListResponse[memoryResponse]{Data: out, Meta: httpx.NewPageMeta(page.Page, page.PageSize, page.Total)})
}

// UpdateMemory handles PATCH /api/v1/owner/memories/:memoryId.
func (h *ConsultationHandler) UpdateMemory(c *gin.Context) {
	userID, memoryID, ok := userAndUUID(c, "memoryId")
	if !ok {
		return
	}
	var req updateMemoryRequest
	if err := bindJSON(c, &req); err != nil {
		handleError(c, err)
		return
	}
	m, err := h.memories.Update(c.Request.Context(), userID, memoryID, service.UpdateMemoryInput{FactText: req.FactText, IsActive: req.IsActive})
	if err != nil {
		handleError(c, err)
		return
	}
	c.JSON(http.StatusOK, httpx.DataResponse[memoryResponse]{Data: newMemoryResponse(m)})
}

// --- DTOs ------------------------------------------------------------------------------

// sessionResponse is a consultation session with its messages. context_snapshot and
// solution are JSON documents whose schema is defined by domain.ContextSnapshot and
// domain.SolutionData (the same documents stored in JSONB).
type sessionResponse struct {
	ID                     string                 `json:"id"`
	ShopID                 string                 `json:"shop_id"`
	IssueID                string                 `json:"issue_id"`
	StartedByUserID        string                 `json:"started_by_user_id"`
	Status                 string                 `json:"status"`
	StateVersion           int64                  `json:"state_version"`
	QuestionCount          int16                  `json:"question_count"`
	AskedTopics            []string               `json:"asked_topics"`
	SkippedTopics          []string               `json:"skipped_topics"`
	IsProcessing           bool                   `json:"is_processing"`
	FinalSolutionMessageID *string                `json:"final_solution_message_id"`
	ContextSnapshot        domain.ContextSnapshot `json:"context_snapshot"`
	Messages               []messageResponse      `json:"messages"`
	Replayed               bool                   `json:"replayed"`
	CreatedAt              time.Time              `json:"created_at"`
	UpdatedAt              time.Time              `json:"updated_at"`
	ArchivedAt             *time.Time             `json:"archived_at"`
}

type memoryCandidateResponse struct {
	FactText              string   `json:"fact_text"`
	SourceOwnerMessageIDs []string `json:"source_owner_message_ids"`
}

// messageResponse is one consultation message.
type messageResponse struct {
	ID               string                    `json:"id"`
	Role             string                    `json:"role"`
	MessageType      string                    `json:"message_type"`
	Content          *string                   `json:"content"`
	Solution         *domain.SolutionData      `json:"solution"`
	Revision         *int                      `json:"revision"`
	TopicKey         *string                   `json:"topic_key"`
	ModelID          *string                   `json:"model_id"`
	PromptVersion    *string                   `json:"prompt_version"`
	MemoryCandidates []memoryCandidateResponse `json:"memory_candidates"`
	RequestID        *string                   `json:"request_id"`
	CreatedAt        time.Time                 `json:"created_at"`
}

func newSessionResponse(v service.SessionView) sessionResponse {
	s := v.Session
	out := sessionResponse{
		ID:                     s.ID.String(),
		ShopID:                 s.ShopID.String(),
		IssueID:                s.IssueID.String(),
		StartedByUserID:        s.StartedByUserID.String(),
		Status:                 string(s.Status),
		StateVersion:           s.StateVersion,
		QuestionCount:          s.QuestionCount,
		AskedTopics:            nonNil(s.AskedTopics),
		SkippedTopics:          nonNil(s.SkippedTopics),
		IsProcessing:           s.ProcessingRequestID != nil,
		FinalSolutionMessageID: optionalUUID(s.FinalSolutionMessageID),
		ContextSnapshot:        s.ContextSnapshot.V,
		Messages:               make([]messageResponse, 0, len(v.Messages)),
		Replayed:               v.Replayed,
		CreatedAt:              s.CreatedAt,
		UpdatedAt:              s.UpdatedAt,
		ArchivedAt:             s.ArchivedAt,
	}
	for _, m := range v.Messages {
		out.Messages = append(out.Messages, newMessageResponse(m))
	}
	return out
}

func newMessageResponse(m domain.ConsultationMessage) messageResponse {
	out := messageResponse{
		ID:               m.ID.String(),
		Role:             string(m.Role),
		MessageType:      string(m.MessageType),
		Content:          m.Content,
		Revision:         m.Revision,
		TopicKey:         m.TopicKey,
		ModelID:          m.ModelID,
		PromptVersion:    m.PromptVersion,
		MemoryCandidates: make([]memoryCandidateResponse, 0, len(m.MemoryCandidates.V)),
		RequestID:        optionalUUID(m.RequestID),
		CreatedAt:        m.CreatedAt,
	}
	if m.SolutionData.Valid {
		sol := m.SolutionData.V
		out.Solution = &sol
	}
	for _, c := range m.MemoryCandidates.V {
		out.MemoryCandidates = append(out.MemoryCandidates, memoryCandidateResponse{
			FactText: c.FactText, SourceOwnerMessageIDs: uuidStrings(c.SourceOwnerMessageIDs),
		})
	}
	return out
}

// memoryResponse is a business memory.
type memoryResponse struct {
	ID                    string    `json:"id"`
	ShopID                string    `json:"shop_id"`
	FactText              string    `json:"fact_text"`
	SourceSessionID       string    `json:"source_session_id"`
	SourceOwnerMessageIDs []string  `json:"source_owner_message_ids"`
	ConfirmedByUserID     string    `json:"confirmed_by_user_id"`
	ConfirmedAt           time.Time `json:"confirmed_at"`
	IsActive              bool      `json:"is_active"`
	CreatedAt             time.Time `json:"created_at"`
	UpdatedAt             time.Time `json:"updated_at"`
}

func newMemoryResponse(m domain.BusinessMemory) memoryResponse {
	return memoryResponse{
		ID:                    m.ID.String(),
		ShopID:                m.ShopID.String(),
		FactText:              m.FactText,
		SourceSessionID:       m.SourceSessionID.String(),
		SourceOwnerMessageIDs: uuidStrings(m.SourceOwnerMessageIDs.V),
		ConfirmedByUserID:     m.ConfirmedByUserID.String(),
		ConfirmedAt:           m.ConfirmedAt,
		IsActive:              m.IsActive,
		CreatedAt:             m.CreatedAt,
		UpdatedAt:             m.UpdatedAt,
	}
}

// saveConsultationResponse is the archived session and the memories created.
type saveConsultationResponse struct {
	Session  sessionResponse  `json:"session"`
	Memories []memoryResponse `json:"memories"`
}

func uuidStrings(ids []uuid.UUID) []string {
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = id.String()
	}
	return out
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}
